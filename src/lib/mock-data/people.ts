export const MEMBERS_BY_ID: Record<string, AppUser> = Object.fromEntries(
  MEMBERS.map((m) => [m.id, m])
);

export function memberName(memberId: string) {
  return MEMBERS_BY_ID[memberId]?.fullName ?? "Unknown Member";
}

export function memberInitials(memberId: string) {
  return MEMBERS_BY_ID[memberId]?.avatarInitials ?? "?";
}

